export function wanfangGardenPathSamples(path,subdivisions=8){
 const points=path.points,out=[];
 if(points.length<2)throw new Error('A garden walk requires distinct endpoints.');
 for(let i=0;i<points.length-1;i++){
  const a=points[Math.max(0,i-1)],b=points[i],c=points[i+1],d=points[Math.min(points.length-1,i+2)];
  for(let k=0;k<subdivisions;k++){
   const t=k/subdivisions,t2=t*t,t3=t2*t;
   out.push(b.map((v,axis)=>.5*(2*v+(-a[axis]+c[axis])*t+(2*a[axis]-5*v+4*c[axis]-d[axis])*t2+(-a[axis]+3*v-3*c[axis]+d[axis])*t3)));
  }
 }
 out.push([...points[points.length-1]]);return out;
}
