// Bakes the Academy map into the small runtime data used by the lean game:
//   src/academy/terrain.bin      heightfield (Uint16, 1 m grid) sampled from world.js terrainHeight
//   src/academy/baked-layout.js  path polylines from landform-layout.js
// The procedural terrain function costs ~6 µs per call and pulls in the whole
// heavy world module graph; the game samples this grid instead.
//
//   node world/scripts/bake-academy-terrain.mjs
import fs from 'node:fs';
import {terrainHeight} from '../src/world.js';
import {academyPathCurves} from '../src/landform-layout.js';
import {locations} from '../src/locations.js';
import {HEIGHTFIELD} from '../src/academy/heightfield.js';

const {size,origin,step,offset,scale}=HEIGHTFIELD;
const data=new Uint16Array(size*size);
let min=Infinity,max=-Infinity;
for(let j=0;j<size;j++)for(let i=0;i<size;i++){
  const h=terrainHeight(origin+i*step,origin+j*step);
  min=Math.min(min,h);max=Math.max(max,h);
  data[j*size+i]=Math.round((h+offset)*scale);
}
const out=new URL('../src/academy/',import.meta.url);
fs.writeFileSync(new URL('terrain.bin',out),Buffer.from(data.buffer));

const round=v=>Math.round(v*100)/100;
const paths=[];
for(const location of locations)for(const curve of academyPathCurves(location)){
  const points=curve.getPoints(Math.max(2,Math.ceil(curve.getLength()/2)));
  paths.push({id:location.id,width:location.id==='about'?3.2:2,points:points.map(p=>[round(p.x),round(p.z)])});
}
fs.writeFileSync(new URL('baked-layout.js',out),`// Generated by scripts/bake-academy-terrain.mjs. Do not edit by hand.\nexport const BAKED_PATHS=${JSON.stringify(paths)};\n`);
console.log(`terrain.bin ${size}x${size}, height ${min.toFixed(2)}..${max.toFixed(2)} m; ${paths.length} paths`);
